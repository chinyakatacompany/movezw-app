import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { test } from 'node:test';

test('registration, bids, ring and accepted-only communications are enforced by Postgres', async () => {
 const db = new PGlite();
 try {
 await db.exec(`
 create role anon; create role authenticated; create role service_role;
 create schema auth; create schema vault; create schema net; create schema cron;
 create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema public,auth to authenticated,anon;
 create table vault.decrypted_secrets(name text,decrypted_secret text);
 create function net.http_post(url text,headers jsonb,body jsonb,timeout_milliseconds int) returns bigint language sql as 'select 1::bigint';
 create function cron.schedule(text,text,text) returns bigint language sql as 'select 1::bigint';
 create table profiles(id uuid primary key,full_name text,role text,is_suspended boolean default false,deleted_at timestamptz,created_at timestamptz default now());
 create function is_admin() returns boolean language sql security definer set search_path=public as $$select exists(select 1 from profiles where id=auth.uid() and role='admin')$$;
 create table driver_profiles(user_id uuid,verification_status text);
 create table transport_requests(id uuid primary key,customer_id uuid,accepted_driver_id uuid,status text);
 create table offers(id uuid primary key default gen_random_uuid(),request_id uuid,driver_id uuid,status text,price numeric,eta_minutes int);
 create table notifications(id uuid primary key default gen_random_uuid(),user_id uuid,type text,title text,message text,link text,is_read boolean default false,created_at timestamptz default now());
 create table conversations(id uuid primary key default gen_random_uuid(),request_id uuid,customer_id uuid,driver_id uuid,last_message text);
 create table messages(id uuid primary key default gen_random_uuid(),conversation_id uuid,sender_id uuid,text text);
 alter table notifications enable row level security;
 alter table conversations enable row level security;
 alter table messages enable row level security;
 grant select,insert,update on conversations,messages,notifications to authenticated;
 create policy existing_notifications on notifications for all to authenticated using(user_id=auth.uid()) with check(true);
 create policy existing_conversations on conversations for all to authenticated using(auth.uid() in(customer_id,driver_id) or is_admin()) with check(auth.uid() in(customer_id,driver_id));
 create policy existing_messages on messages for all to authenticated using(true) with check(sender_id=auth.uid());
 `);
 let sql = await readFile(new URL('../migrations/20261023103823_registration_alerts_and_private_calls.sql', import.meta.url),'utf8');
 sql = sql.replace(/do \$\$ begin\s*alter publication[\s\S]*?end \$\$;/,'');
 await db.exec(sql);
 const admin='00000000-0000-4000-8000-000000000001',customer='00000000-0000-4000-8000-000000000002',driver='00000000-0000-4000-8000-000000000003',stranger='00000000-0000-4000-8000-000000000004',job='00000000-0000-4000-8000-000000000005';
 for(const [id,role] of [[admin,'admin'],[customer,'customer'],[driver,'driver'],[stranger,'customer']]) {
   await db.query('insert into auth.users(id,email) values($1,$2)',[id,`${role}@example.test`]);
   await db.query('insert into profiles(id,role,full_name) values($1,$2,$2)',[id,role]);
 }
 const scalar=async sql => Object.values((await db.query(sql)).rows[0])[0];
 assert.equal(await scalar("select count(*)::int from notifications where type='driver_registered'"),1);
 assert.equal(await scalar("select count(*)::int from app_push_outbox"),1);
 const asUser=async id => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]); await db.exec('set role authenticated'); };
 await asUser(admin);
 const directory=await scalar('select admin_user_directory()');
 assert.equal(directory.find(p=>p.id===driver).email_confirmed_at,null,'admin sees driver before confirmation');
 await asUser(driver); await assert.rejects(db.query('select admin_user_directory()'),/Administrator access required/);
 await db.exec('reset role');
 await db.query("insert into driver_profiles values($1,'approved')",[driver]);
 await db.query("insert into transport_requests values($1,$2,null,'open')",[job,customer]);
 await db.query("insert into offers(request_id,driver_id,status,price) values($1,$2,'pending',25)",[job,driver]);
 assert.equal(await scalar("select count(*)::int from notifications where type='new_offer'"),1);
 await db.exec('update offers set price=30');
 assert.equal(await scalar("select count(*)::int from notifications where type='new_offer'"),2,'bid revisions notify customer');
 await asUser(driver);
 await assert.rejects(db.query('select start_job_call($1)',[job]),/Calls unlock/);
 await assert.rejects(db.query('insert into conversations(request_id,customer_id,driver_id) values($1,$2,$3)',[job,customer,driver]),/row-level security/);
 await assert.rejects(db.query("insert into notifications(user_id,type) values($1,'job_ring')",[customer]),/row-level security/);
 await db.query('select ring_job_party($1,$2)',[job,customer]);
 await assert.rejects(db.query('select ring_job_party($1,$2)',[job,customer]),/wait a minute/);
 await asUser(stranger); await assert.rejects(db.query('select ring_job_party($1,$2)',[job,customer]),/pending bid/);
 await db.exec('reset role');
 const ring=(await db.query("select * from notifications where type='job_ring'")).rows[0];
 assert.equal(ring.message,'Please review this transport job. Voice and chat unlock only after acceptance.');
 await db.query("update transport_requests set accepted_driver_id=$1,status='confirmed'",[driver]);
 await asUser(customer);
 const conv=(await db.query('insert into conversations(request_id,customer_id,driver_id) values($1,$2,$3) returning id',[job,customer,driver])).rows[0].id;
 await db.query("insert into messages(conversation_id,sender_id,text) values($1,$2,'Accepted job message')",[conv,customer]);
 const call=(await db.query('select * from start_job_call($1)',[job])).rows[0];
 assert.equal(call.callee_id,driver);
 await assert.rejects(db.query("select respond_job_call($1,'accept')",[call.id]),/cannot be accepted/);
 await assert.rejects(db.query("insert into job_call_signals(call_id,sender_id,kind,payload) values($1,$2,'offer','{}')",[call.id,customer]),/permission denied/);
 await asUser(stranger);
 assert.equal(await scalar('select count(*)::int from job_calls'),0);
 await assert.rejects(db.query("select send_job_call_signal($1,'ice','{}')",[call.id]),/not active/);
 await assert.rejects(db.query("insert into messages(conversation_id,sender_id,text) values($1,$2,'Attack')",[conv,stranger]),/row-level security/);
 await asUser(driver);
 await db.query("select respond_job_call($1,'accept')",[call.id]);
 await db.query("select send_job_call_signal($1,'answer',$2)",[call.id,{type:'answer',sdp:'v=0\nm=audio 9 UDP/TLS/RTP/SAVPF 111'}]);
 await asUser(customer);
 await assert.rejects(db.query("select send_job_call_signal($1,'offer',$2)",[call.id,{sdp:'m=audio 9\nm=video 9'}]),/Audio calls only/);
 await db.query("select send_job_call_signal($1,'offer',$2)",[call.id,{type:'offer',sdp:'v=0\nm=audio 9 UDP/TLS/RTP/SAVPF 111'}]);
 await db.exec('reset role');
 await db.query("update transport_requests set status='cancelled' where id=$1",[job]);
 await asUser(customer);
 assert.equal(await scalar('select count(*)::int from conversations'),0,'cancelled jobs cannot use old conversations');
 await assert.rejects(db.query("select send_job_call_signal($1,'ice','{}')",[call.id]),/not active/);
 await db.exec('reset role');
 await db.exec('begin');
 await db.query("insert into offers(request_id,driver_id,status,price) values($1,$2,'pending',40)",[job,driver]);
 await db.exec('rollback');
 assert.equal(await scalar("select count(*)::int from notifications where type='new_offer'"),2);
 } finally { await db.close(); }
});
